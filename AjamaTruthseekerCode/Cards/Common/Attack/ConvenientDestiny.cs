namespace AjamaTruthseeker.AjamaTruthseekerCode.Cards.Common.Attack;

public class ConvenientDestiny() : AjamaTruthseekerCard(1,
    CardType.Attack, CardRarity.Common,
    TargetType.AnyEnemy)
{
    protected override IEnumerable<DynamicVar> CanonicalVars =>
    [
        new DamageVar(5, DamageProps.card),
        new CardsVar(1)
    ];

    public override List<NonDynamicEffect> MyNonDynamicEffects =>
    [
        NonDynamicEffect.Rewrite
    ];

    protected override async Task OnPlay(
        PlayerChoiceContext choiceContext,
        CardPlay play)
    {
        await CommonActions.CardAttack(this, play,
                vfx: VfxCmd.slashPath,
                tmpSfx: TmpSfx.slashAttack)
            .Execute(choiceContext);

        await MyActions.Rewrite(choiceContext, Owner);

        await MyActions.Draw(choiceContext, this);
    }

    protected override void OnUpgrade()
    {
        DynamicVars.Damage.UpgradeValueBy(3);
    }
}